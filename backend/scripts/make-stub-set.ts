// Generates challenges/stub-001: 3 rounds of tiny placeholder PNGs (solid colors + a shape).
// Usage: npm run stub:images [-- <outDir>]
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { encodePng, type RgbaImage } from "../src/lib/image.ts";

type Rgb = [number, number, number];
type Shape =
  | { kind: "circle"; cx: number; cy: number; r: number; color: Rgb }
  | { kind: "square"; x: number; y: number; size: number; color: Rgb }
  | { kind: "triangle"; cx: number; cy: number; size: number; color: Rgb };

const SIZE = 128;

function paint(bg: Rgb, shapes: Shape[]): RgbaImage {
  const data = new Uint8Array(SIZE * SIZE * 4);
  for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
      let c = bg;
      for (const s of shapes) if (inside(s, x + 0.5, y + 0.5)) c = s.color;
      const i = (y * SIZE + x) * 4;
      data[i] = c[0];
      data[i + 1] = c[1];
      data[i + 2] = c[2];
      data[i + 3] = 255;
    }
  }
  return { width: SIZE, height: SIZE, data };
}

function inside(s: Shape, x: number, y: number): boolean {
  if (s.kind === "circle") return (x - s.cx) ** 2 + (y - s.cy) ** 2 <= s.r ** 2;
  if (s.kind === "square") return x >= s.x && x < s.x + s.size && y >= s.y && y < s.y + s.size;
  // Upward-pointing isosceles triangle centred at (cx, cy).
  const h = s.size;
  const top = s.cy - h / 2;
  const bottom = s.cy + h / 2;
  if (y < top || y > bottom) return false;
  const half = ((y - top) / h) * (s.size / 2);
  return x >= s.cx - half && x <= s.cx + half;
}

const stars: Shape[] = [
  [20, 18], [100, 22], [40, 100], [110, 96], [70, 12], [14, 70],
].map(([cx, cy]) => ({ kind: "circle" as const, cx, cy, r: 2.5, color: [255, 255, 220] as Rgb }));

const rounds = [
  {
    before: paint([40, 90, 200], [{ kind: "circle", cx: 64, cy: 64, r: 30, color: [250, 210, 40] }]),
    target: paint([240, 120, 40], [{ kind: "circle", cx: 64, cy: 64, r: 30, color: [250, 210, 40] }]),
    originalPrompt: "same composition, background turned to a warm orange sunset, keep the yellow circle exactly as it is",
    clue: "The sky grew tired of blue and borrowed the sun's last coat.",
    tip: "Name the change, then name what must stay the same.",
  },
  {
    before: paint([60, 160, 80], [{ kind: "square", x: 34, y: 34, size: 60, color: [220, 40, 40] }]),
    target: paint([60, 160, 80], [{ kind: "triangle", cx: 64, cy: 64, size: 64, color: [220, 40, 40] }]),
    originalPrompt: "replace the red square with a red triangle pointing up, same size, same green background",
    clue: "Four corners walked into a bar. Only three walked out.",
    tip: "Shape words beat vague words: say exactly which shape it becomes.",
  },
  {
    before: paint([245, 245, 245], [{ kind: "circle", cx: 64, cy: 64, r: 26, color: [20, 20, 20] }]),
    target: paint([15, 20, 60], [...stars, { kind: "circle", cx: 64, cy: 64, r: 26, color: [250, 250, 235] }]),
    originalPrompt: "night version: dark navy sky with small stars, the black circle becomes a glowing pale moon",
    clue: "When the lights go out, the shadow learns to shine.",
    tip: "Describe the mood and the lighting, not just the objects.",
  },
];

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(process.argv[2] ?? join(here, "..", "..", "challenges", "stub-001"));

const setJson = {
  id: "stub-001",
  title: "Stub Set: Shapes in Peril",
  description: "Placeholder set so the pipeline runs end to end. Generated by backend/scripts/make-stub-set.ts.",
  difficulty: "easy",
  tags: ["stub", "shapes"],
  author: "pwd-team",
  rounds: rounds.map((r, i) => {
    const dir = join(outDir, `r${i + 1}`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "before.png"), encodePng(r.before));
    writeFileSync(join(dir, "target.png"), encodePng(r.target));
    return {
      before: `r${i + 1}/before.png`,
      target: `r${i + 1}/target.png`,
      originalPrompt: r.originalPrompt,
      modelId: "stub/solid-shapes",
      modelParams: { seed: i + 1, size: SIZE },
      clue: r.clue,
      tip: r.tip,
    };
  }),
};

writeFileSync(join(outDir, "set.json"), JSON.stringify(setJson, null, 2) + "\n");
console.log(`wrote ${outDir}`);
